const EMOJI_LIBRARY_SET = new Set(EMOJI_LIBRARY);

/**
 * Whether an emoji is one of the offered ones (the signup route's allowlist).
 * The set is built once at module load from the single source of truth.
 */
export function isEmojiInLibrary(emoji: string): boolean {
  return EMOJI_LIBRARY_SET.has(emoji);
}

/**
 * A uniform random draw from EMOJI_LIBRARY, never returning `current`.
 * `random` is injectable for deterministic tests (same convention as the
 * Match 2 picker); plain Math.random is fine at the call site -- this is a
 * personalization draw, not a security one.
 */
export function pickRandomEmoji(
  current: string | null,
  random: () => number = Math.random,
): string {
  const pool =
    current === null
      ? EMOJI_LIBRARY
      : EMOJI_LIBRARY.filter((emoji) => emoji !== current);
  return pool[Math.floor(random() * pool.length)];
}
